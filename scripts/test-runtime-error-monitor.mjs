import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here=dirname(fileURLToPath(import.meta.url));
const index=readFileSync(resolve(here,'../index.html'),'utf8');
const match=index.match(/<script id="haldo-v167-runtime-error-monitor">([\s\S]*?)<\/script>/);
assert.ok(match,'Runtime Error Monitor script exists');
const listeners={};
const H={Registry:{featured:[]},Win:{open(){}},Launch:function(){return 'previous-launch';}};
const window={HalDo:H,addEventListener(type,fn){(listeners[type]??=[]).push(fn);},setTimeout(){},URL:{createObjectURL(){return 'blob:test';},revokeObjectURL(){}}};
const document={createElement(){return {click(){},remove(){}};},body:{appendChild(){}},getElementById(){return null;}};
runInNewContext(match[1],{window,document,Blob,Date,JSON,String,Number,Object,Array,RegExp});
const monitor=H.RuntimeErrorMonitor;
assert.ok(monitor&&monitor.installed,'monitor installs without replacing global handlers');
assert.equal(listeners.error.length,1);
assert.equal(listeners.unhandledrejection.length,1);
assert.equal(listeners.warning,undefined,'console warnings are not subscribed to');
listeners.error[0]({message:'TypeError: failed',filename:'app.js?token=abc123',lineno:12,colno:4,error:{stack:'TypeError: failed\n at app.js?api_key=secret'}});
listeners.unhandledrejection[0]({reason:{message:'Promise failed',stack:'Error: Promise failed'}});
let data=monitor.list();
assert.equal(data.length,2);
assert.equal(data[0].type,'runtime');
assert.equal(data[1].type,'unhandled-rejection');
assert.match(data[0].source,/\[REDACTED\]/);
assert.match(data[0].stack,/\[REDACTED\]/);
assert.deepEqual({...monitor.summary()},{total:2,runtime:1,unhandledRejections:1,limit:100});
for(let i=0;i<110;i++)monitor.capture({type:'manual',message:'event '+i});
assert.equal(monitor.list().length,100,'ring buffer remains bounded');
assert.equal(monitor.list()[0].message,'event 10');
assert.equal(monitor.report().product,'HalDo Runtime Error Monitor Pro');
assert.match(monitor.report().scope,/Keine automatische Übertragung/);
assert.equal(monitor.clear().total,0);
assert.ok(H.Registry.featured.some(x=>x.id==='runtime-error-monitor'));
assert.equal(H.Launch({id:'runtime-error-monitor'}),false,'open safely reports unavailable window UI');
assert.equal(H.Launch({id:'other'}),'previous-launch','previous launcher remains chained');
console.log('Runtime Error Monitor contract tests passed: event capture, rejection separation, redaction, bounded storage, report, clear and launcher chaining.');
